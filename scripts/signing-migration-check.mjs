import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { releaseManifests } from './create-release-manifests.mjs';
import { LEGACY_APK_PREFIX } from './android-update-manifest.mjs';

const readJson = async path => JSON.parse((await readFile(new URL(path, import.meta.url), 'utf8')).replace(/^\uFEFF/, ''));
const identity = await readJson('../release/signing-identity.json');
const legacy = await readJson('../release/legacy-1.23.1.json');
const config = await readJson('../src-tauri/tauri.conf.json');
const androidConfig = await readJson('../src-tauri/tauri.android.conf.json');
const version = config.version;
assert.equal(config.identifier, 'com.oscard0823.cajafantasma', 'Windows must retain its existing data directory.');
assert.equal(androidConfig.identifier, identity.androidApplicationId);
assert.notEqual(androidConfig.identifier, config.identifier, 'The Android replacement must coexist with the app signed by the lost key.');
assert.equal(config.plugins.updater.pubkey, identity.windowsPublicKey);
assert(config.plugins.updater.endpoints.every(url => url.endsWith('/latest-v2.json')));
const kotlin = await readFile(new URL('../plugins/android-updater/android/src/main/java/AndroidUpdaterPlugin.kt', import.meta.url), 'utf8');
assert(kotlin.includes('/latest-v2.json'));
const android = { url: `${LEGACY_APK_PREFIX}v${version}/Caja-Fantasma-Android-${version}.apk`, sha256: 'A'.repeat(64), architecture: 'arm64-v8a', minimum_android: 8 };
const input = { version, signature: 'new-signature-fixture', android, notes: 'migration', identity, legacy };
const { current, previous } = releaseManifests(input);
assert.equal(current.version, version);
assert.equal(current.android.application_id, identity.androidApplicationId);
assert.equal(previous.version, '1.23.1');
assert.deepEqual(previous.platforms, legacy.platforms, 'Old clients must keep the installer and valid old signature.');
assert.deepEqual(previous.android, legacy.android, 'Old clients must never be offered the new Android identity.');
assert(previous.android.url.startsWith(LEGACY_APK_PREFIX));
assert(previous.android.url.includes('/v1.23.1/'));
assert.equal(legacy.migration, undefined, 'Manifest generation must not mutate the frozen legacy snapshot.');
assert.throws(() => releaseManifests({ ...input, identity: { ...identity, androidApplicationId: config.identifier } }));
assert.throws(() => releaseManifests({ ...input, identity: { ...identity, androidCertificateSha256: '' } }));
assert.throws(() => releaseManifests({ ...input, legacy: { ...legacy, version } }));
console.log('Signing migration OK: Windows profile retained, Android coexistence, new update channel and intact legacy manifests.');
